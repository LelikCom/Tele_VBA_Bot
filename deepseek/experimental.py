def back_keyboard() -> InlineKeyboardMarkup:
    """Кнопка «Назад» (пока просто возвращаемся к предыдущему сообщению)."""
    return InlineKeyboardMarkup([
        [InlineKeyboardButton("⬅️ Назад", callback_data="back_to_prev")]
    ])
